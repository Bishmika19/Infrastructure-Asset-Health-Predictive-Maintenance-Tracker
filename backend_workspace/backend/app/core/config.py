"""Typed runtime settings for the backend.

Names reuse the keys already defined in ``.project_manifest.yaml``. Database
URLs are resolved from the process environment first; when absent they are read
from the ``database_urls.env`` file generated by the workspace database
container (``database_workspace/database/startup.sh``). Secrets are never logged:
the URL fields are excluded from ``repr``.
"""

from __future__ import annotations

import json
import logging
import os
import secrets
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional

from dotenv import dotenv_values, load_dotenv

logger = logging.getLogger(__name__)

MIN_TOKEN_SECRET_LENGTH = 32

# backend_workspace/backend (``app/core/config.py`` -> parents[2]).
BACKEND_ROOT = Path(__file__).resolve().parents[2]
# Workspace root that also contains ``database_workspace``.
WORKSPACE_ROOT = BACKEND_ROOT.parents[1]
DEFAULT_DATABASE_URLS_FILE = WORKSPACE_ROOT / "database_workspace" / "database" / "database_urls.env"
# Persistent signing secret kept OUTSIDE the workspace and git (the platform resets workspace file
# modes to 0777, so a protected 0600 file must live under the user's home). Created by
# ``python -m scripts.provision_auth_secret``; override the location with AUTH_TOKEN_SECRET_FILE.
DEFAULT_AUTH_SECRET_FILE = Path.home() / ".local" / "share" / "asset-health-backend" / "auth_token_secret"

load_dotenv(BACKEND_ROOT / ".env")


def _csv(name: str, default: str) -> List[str]:
    """Parse a comma-separated environment variable into a clean list."""
    raw = os.getenv(name, default)
    return [item.strip() for item in raw.split(",") if item.strip()]


def _bool(name: str, default: bool = False) -> bool:
    """Parse a boolean environment variable."""
    return os.getenv(name, str(default)).strip().lower() in {"1", "true", "yes", "on"}


def _json_object(name: str) -> Dict[str, Any]:
    """Parse a JSON-object environment variable, ignoring malformed values."""
    try:
        value = json.loads(os.getenv(name, "{}") or "{}")
    except ValueError:
        return {}
    return value if isinstance(value, dict) else {}


def _database_urls_file_values() -> Dict[str, Optional[str]]:
    """Read the generated database URL file, if it exists."""
    path = Path(os.getenv("DATABASE_URLS_FILE", str(DEFAULT_DATABASE_URLS_FILE)))
    if path.is_file():
        return dict(dotenv_values(path))
    return {}


def _resolve_url(name: str) -> Optional[str]:
    """Resolve a database URL: environment first, then the generated file."""
    value = os.getenv(name) or _database_urls_file_values().get(name)
    return value or None


def _resolve_auth_secret() -> str:
    """Resolve the token secret: AUTH_TOKEN_SECRET env, then the protected secret file, else ''."""
    value = os.getenv("AUTH_TOKEN_SECRET", "").strip()
    if value:
        return value
    path = Path(os.getenv("AUTH_TOKEN_SECRET_FILE", str(DEFAULT_AUTH_SECRET_FILE)))
    try:
        return path.read_text(encoding="utf-8").strip() if path.is_file() else ""
    except OSError:
        # Unreadable file: fall back to the ephemeral development secret (never log contents).
        logger.warning("AUTH_TOKEN_SECRET_FILE could not be read")
        return ""


@dataclass(frozen=True)
class Settings:
    """Immutable settings snapshot shared by the API and the worker."""

    healthcheck_path: str = "/healthz"
    log_level: str = "info"
    trust_proxy: bool = False
    feature_flags: Dict[str, Any] = field(default_factory=dict)
    experiments_enabled: bool = False
    allowed_origins: List[str] = field(default_factory=list)
    allowed_headers: List[str] = field(default_factory=list)
    allowed_methods: List[str] = field(default_factory=list)
    cors_max_age: int = 3600
    # Runtime role (asset_app): DML only. Never logged.
    database_url: Optional[str] = field(default=None, repr=False)
    # Migration role (asset_migrator): DDL for Alembic only. Never logged.
    migration_database_url: Optional[str] = field(default=None, repr=False)
    # Bounded pool with a finite wait (DEC-12).
    db_pool_size: int = 5
    db_max_overflow: int = 5
    db_pool_timeout_s: int = 10
    # Transport limits (DEC-11): 16 KiB JSON bodies, larger cap for photo uploads.
    max_json_body_bytes: int = 16 * 1024
    max_multipart_body_bytes: int = 110_000_000
    # Local disk adapter root for development only; production needs a managed adapter (OD-03).
    photo_storage_root: Path = field(
        default_factory=lambda: Path.home() / ".local" / "share" / "asset-health-photos"
    )
    # Bearer-token signing secret (AUTH_TOKEN_SECRET, at least 32 characters). Never logged.
    auth_token_secret: str = field(default="", repr=False)
    # True when no secret was configured and a per-process random one was generated (dev only).
    auth_token_secret_ephemeral: bool = False
    auth_token_ttl_s: int = 3600
    # Login throttling (A-3, DEC-04): failures counted from audit_logs inside the window.
    login_max_failures_per_username: int = 5
    login_max_failures_per_ip: int = 20
    login_window_s: int = 900
    # Idempotency records are retained for at least 24 hours (DEC-11).
    idempotency_ttl_s: int = 24 * 3600
    # Durable worker configuration. Jobs claim database leases rather than using in-process cron.
    worker_poll_interval_s: int = 30
    worker_lease_s: int = 300
    worker_nightly_batch_size: int = 100
    worker_staging_ttl_s: int = 24 * 3600
    outbox_max_attempts: int = 8
    outbox_backoff_cap_s: int = 3600
    # Email is opt-in: disabled by default to preserve the no-outbound-email deployment choice.
    # Disabled email events are terminally dead-lettered by the worker without contacting SMTP.
    outbound_email_enabled: bool = False
    # SMTP settings are only used when outbound_email_enabled is explicitly true.
    smtp_host: Optional[str] = None
    smtp_port: int = 587
    smtp_username: Optional[str] = field(default=None, repr=False)
    smtp_password: Optional[str] = field(default=None, repr=False)
    smtp_from: str = "noreply@asset-health.local"
    smtp_to: List[str] = field(default_factory=list)
    smtp_starttls: bool = True
    smtp_timeout_s: int = 10


# PUBLIC_INTERFACE
def get_settings() -> Settings:
    """Build a Settings object from the current environment."""
    healthcheck_path = os.getenv("HEALTHCHECK_PATH", "/healthz")
    if not healthcheck_path.startswith("/"):
        healthcheck_path = "/" + healthcheck_path
    token_secret = _resolve_auth_secret()
    ephemeral = not token_secret
    if ephemeral:
        # Development fallback: tokens do not survive a restart and are not shared across replicas.
        token_secret = secrets.token_urlsafe(48)
        logger.warning("AUTH_TOKEN_SECRET is not set; using an ephemeral per-process secret")
    elif len(token_secret) < MIN_TOKEN_SECRET_LENGTH:
        raise ValueError(
            f"The token secret (AUTH_TOKEN_SECRET or AUTH_TOKEN_SECRET_FILE) must be at least "
            f"{MIN_TOKEN_SECRET_LENGTH} characters"
        )
    return Settings(
        healthcheck_path=healthcheck_path,
        log_level=os.getenv("LOG_LEVEL", "info").lower(),
        trust_proxy=_bool("TRUST_PROXY"),
        feature_flags=_json_object("FEATURE_FLAGS"),
        experiments_enabled=_bool("EXPERIMENTS_ENABLED"),
        allowed_origins=_csv("ALLOWED_ORIGINS", "http://localhost:3000"),
        allowed_headers=_csv("ALLOWED_HEADERS", "Content-Type,Authorization,X-Requested-With"),
        allowed_methods=_csv("ALLOWED_METHODS", "GET,POST,PUT,DELETE,PATCH,OPTIONS"),
        cors_max_age=int(os.getenv("CORS_MAX_AGE", "3600")),
        database_url=_resolve_url("DATABASE_URL"),
        migration_database_url=_resolve_url("MIGRATION_DATABASE_URL"),
        db_pool_size=int(os.getenv("DB_POOL_SIZE", "5")),
        db_max_overflow=int(os.getenv("DB_MAX_OVERFLOW", "5")),
        db_pool_timeout_s=int(os.getenv("DB_POOL_TIMEOUT_S", "10")),
        auth_token_secret=token_secret,
        auth_token_secret_ephemeral=ephemeral,
        photo_storage_root=Path(
            os.getenv(
                "PHOTO_STORAGE_ROOT",
                str(Path.home() / ".local" / "share" / "asset-health-photos"),
            )
        ),
        auth_token_ttl_s=int(os.getenv("AUTH_TOKEN_TTL_S", "3600")),
        login_max_failures_per_username=int(os.getenv("LOGIN_MAX_FAILURES_PER_USERNAME", "5")),
        login_max_failures_per_ip=int(os.getenv("LOGIN_MAX_FAILURES_PER_IP", "20")),
        login_window_s=int(os.getenv("LOGIN_WINDOW_S", "900")),
        idempotency_ttl_s=int(os.getenv("IDEMPOTENCY_TTL_S", str(24 * 3600))),
        worker_poll_interval_s=int(os.getenv("WORKER_POLL_INTERVAL_S", "30")),
        worker_lease_s=int(os.getenv("WORKER_LEASE_S", "300")),
        worker_nightly_batch_size=int(os.getenv("WORKER_NIGHTLY_BATCH_SIZE", "100")),
        worker_staging_ttl_s=int(os.getenv("WORKER_STAGING_TTL_S", str(24 * 3600))),
        outbox_max_attempts=int(os.getenv("OUTBOX_MAX_ATTEMPTS", "8")),
        outbox_backoff_cap_s=int(os.getenv("OUTBOX_BACKOFF_CAP_S", "3600")),
        outbound_email_enabled=_bool("OUTBOUND_EMAIL_ENABLED", False),
        smtp_host=os.getenv("SMTP_HOST") or None,
        smtp_port=int(os.getenv("SMTP_PORT", "587")),
        smtp_username=os.getenv("SMTP_USERNAME") or None,
        smtp_password=os.getenv("SMTP_PASSWORD") or None,
        smtp_from=os.getenv("SMTP_FROM", "noreply@asset-health.local"),
        smtp_to=_csv("SMTP_TO", ""),
        smtp_starttls=_bool("SMTP_STARTTLS", True),
        smtp_timeout_s=int(os.getenv("SMTP_TIMEOUT_S", "10")),
    )


@lru_cache(maxsize=1)
def get_cached_settings() -> Settings:
    """Return process-wide settings (cached); tests build Settings directly."""
    return get_settings()
